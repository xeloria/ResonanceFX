"""Turns build/measure.jsonl (tests/measure-engine.sh) into the app's
app/app/src/main/assets/measurements.json: every effect's measured response and numbers, shown
on the app's "Engine measurements" page and published with each release.

    scripts/gen-measurements.py [build/measure.jsonl] [engine version]
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
source = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "build/measure.jsonl"
version = sys.argv[2] if len(sys.argv) > 2 else re.search(
    r'RFX_VERSION_NAME "([^"]+)"', (ROOT / "engine/CMakeLists.txt").read_text()).group(1)

lines = [json.loads(line) for line in source.read_text().splitlines() if line.strip()]
out = {
    "format": "resonancefx.measurements.v1",
    "engine": version,
    "sampleRate": 48000,
    "method": "Each effect alone, at the settings listed, driven through the Android effect interface "
              "exactly as the phone does. Response: steady sines at -24 dBFS. Loudness: pink noise at "
              "-20 dBFS. Distortion: THD (2nd-6th harmonics) of a -12 dBFS sine. Dynamics: a 1 kHz sine "
              "at -3 and -40 dBFS. Width: side/mid energy of a partly correlated signal. Tail: energy "
              "0.3-1.3 s after a click.",
    "freqs": lines[0]["freqs"],
    "effects": lines[1:],
}
target = ROOT / "app/app/src/main/assets/measurements.json"
target.write_text(json.dumps(out, separators=(",", ":")) + "\n")
print(f"{target.relative_to(ROOT)}: {len(out['effects'])} measurements, engine {version}")


# --- Translated prose -------------------------------------------------------------------------
# The numbers stay in measurements.json; every piece of text is mirrored into string resources
# keyed by the English effect name, so translations never drift from the measurements.

def slug(name: str) -> str:
    s = name.lower().replace("&", " and ")
    s = re.sub(r"[^a-z0-9]+", "_", s).strip("_")
    return re.sub(r"_+", "_", s)


def escape(value: str) -> str:
    return (value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            .replace("'", "\\'").replace('"', "&quot;"))


names = {}
settings = {}
used = set()
for effect in out["effects"]:
    key = "measure_" + slug(effect["name"])
    if key in used:
        raise SystemExit(f"duplicate measurement key {key} for {effect['name']!r}")
    used.add(key)
    names[effect["name"]] = key
    settings[effect["name"]] = key + "_settings"

xml = ['<?xml version="1.0" encoding="utf-8"?>',
       '<!-- GENERATED by scripts/gen-measurements.py - do not edit. -->',
       '<resources>',
       f'    <string name="measurement_method">{escape(out["method"])}</string>']
for effect in out["effects"]:
    xml.append(f'    <string name="{names[effect["name"]]}" formatted="false">{escape(effect["name"])}</string>')
    xml.append(f'    <string name="{settings[effect["name"]]}" formatted="false">{escape(effect.get("settings", ""))}</string>')
xml.append('</resources>')
xml_path = ROOT / "app/app/src/main/res/values/measurement_strings.xml"
xml_path.write_text("\n".join(xml) + "\n", encoding="utf-8")

kt = ['// SPDX-License-Identifier: GPL-3.0-or-later',
      '// Copyright (C) 2026 Xeloria',
      '',
      '// GENERATED by scripts/gen-measurements.py - do not edit.',
      'package io.github.resonancefx.model',
      '',
      'import io.github.resonancefx.R',
      '',
      '/** English effect name -> (name, description) string resources for the measurements page. */',
      'object MeasurementStrings {',
      '    val NAMES: Map<String, Int> = mapOf(']
kt += [f'        "{name}" to R.string.{key},' for name, key in names.items()]
kt += ['    )', '', '    val SETTINGS: Map<String, Int> = mapOf(']
kt += [f'        "{name}" to R.string.{key},' for name, key in settings.items()]
kt += ['    )', '}', '']
kt_path = ROOT / "app/app/src/main/java/io/github/resonancefx/model/MeasurementStrings.kt"
kt_path.write_text("\n".join(kt), encoding="utf-8")
print(f"{xml_path.relative_to(ROOT)}: {len(names)} names, {len(settings)} descriptions")
print(f"{kt_path.relative_to(ROOT)}: generated lookup")
